# ---------------- main: texts -> TTS input (polyphone fixes), estimate, then workers ----------------
function Get-Key([string]$text, [string]$lang) {   # same as Lab.speechKey (FNV-1a 32 over UTF-16 code units)
  $s = $lang + '|' + (($text -replace '<[^>]+>', '') -replace '\s+', ' ').Trim()
  [uint64]$h = 2166136261
  foreach ($ch in $s.ToCharArray()) { $h = $h -bxor [uint64][int]$ch; $h = ($h * [uint64]16777619) % [uint64]4294967296 }
  return ('{0:x8}' -f $h)
}
$fix = @{}; $maxLen = 1
foreach ($l in [IO.File]::ReadAllLines((Join-Path $PSScriptRoot "polyfix.tsv"), [Text.Encoding]::UTF8)) {
  if ($l -match '^\s*#' -or -not $l.Trim()) { continue }
  $p = $l -split "`t"
  if ($p.Count -lt 3) { continue }
  if ($p[0].Length -ne $p[2].Length) { "polyfix: length mismatch, skipped: $l"; continue }
  $fix[$p[0]] = $p[2]; if ($p[0].Length -gt $maxLen) { $maxLen = $p[0].Length }
}
function Get-Match([string]$t, [int]$i) {   # length of the longest polyfix word starting at $i (0 = none)
  for ($L = [Math]::Min($maxLen, $t.Length - $i); $L -ge 1; $L--) { if ($fix.ContainsKey($t.Substring($i, $L))) { return $L } }
  return 0
}
function Fix-Poly([string]$t) {
  # Longest match, left to right. A match is NOT applied when another listed word starts inside it and runs past its
  # end (e.g. "doctor + long-term": the rule for sheng-zhang overlaps chang-qi) - such ambiguous spots are left exactly as written.
  $sb = New-Object Text.StringBuilder; $i = 0
  while ($i -lt $t.Length) {
    $L = Get-Match $t $i
    if ($L -gt 0) {
      $clash = $false
      for ($s = $i + 1; $s -lt $i + $L -and -not $clash; $s++) { $L2 = Get-Match $t $s; if ($L2 -gt 0 -and $s + $L2 -gt $i + $L) { $clash = $true } }
      if (-not $clash) { [void]$sb.Append($fix[$t.Substring($i, $L)]); $i += $L; continue }
    }
    [void]$sb.Append($t[$i]); $i++
  }
  return $sb.ToString()
}
# ---- maths read aloud in words (mathspeak_<lang>.tsv): TeX in MathAnim narration, and symbols such as = x2 sqrt in any text ----
$MS = @{}
$msf = Join-Path $PSScriptRoot "mathspeak_$Lang.tsv"
if (Test-Path $msf) { foreach ($l in [IO.File]::ReadAllLines($msf, [Text.Encoding]::UTF8)) { if ($l -match '^\s*#' -or -not $l.Trim()) { continue }; $p = $l -split "`t", 2; if ($p.Count -eq 2) { $MS[$p[0]] = $p[1] } } }
function Fill([string]$tpl, [hashtable]$h) { foreach ($k in $h.Keys) { $tpl = $tpl.Replace('{' + $k + '}', $h[$k]) }; return $tpl }
$texCmds = @($MS.Keys | Where-Object { $_.StartsWith('\') } | Sort-Object Length -Descending)
$plainSyms = @($MS.Keys | Where-Object { -not $_.StartsWith('\') -and $_ -notmatch '^[a-z0-9]+$' -and $_ -notmatch '^[=<>]$' } | Sort-Object Length -Descending)
function Speak-Tex([string]$s) {
  $s = $s.Replace([string][char]0x2212, '-')
  $s = $s -replace '\\(left|right|bigg|big|Bigg|Big|displaystyle|quad|qquad)(?![a-zA-Z])', ' '
  $s = $s -replace '\\[,;:! ]', ' '
  $s = $s -replace '\\(text|mathrm|mathbf|textbf|operatorname|mathit|overline|vec|hat|bar)\s*\{([^{}]*)\}', '$2'
  $s = $s -replace '\^\s*\{?\s*\\circ\s*\}?', ' \degree '
  $s = $s -replace '(\d)\s*(?=\\[dt]?frac)', ('$1' + $MS['mixed'])
  for ($n = 0; $n -lt 6; $n++) {
    $s = [regex]::Replace($s, '\\[dt]?frac\s*(?:\{([^{}]*)\}|(\w))\s*(?:\{([^{}]*)\}|(\w))', [Text.RegularExpressions.MatchEvaluator]{ param($m)
      $a = if ($m.Groups[1].Success) { $m.Groups[1].Value } else { $m.Groups[2].Value }
      $b = if ($m.Groups[3].Success) { $m.Groups[3].Value } else { $m.Groups[4].Value }
      ' ' + (Fill $MS['frac'] @{ a = $a.Trim(); b = $b.Trim() }) + ' ' })
    $s = [regex]::Replace($s, '\\sqrt\s*(?:\{([^{}]*)\}|(\w+))', [Text.RegularExpressions.MatchEvaluator]{ param($m)
      $x = if ($m.Groups[1].Success) { $m.Groups[1].Value } else { $m.Groups[2].Value }
      ' ' + (Fill $MS['sqrt'] @{ x = $x.Trim() }) + ' ' })
  }
  $s = $s -replace '\^\s*\{\s*2\s*\}|\^\s*2(?!\d)', $MS['pow2']
  $s = $s -replace '\^\s*\{\s*3\s*\}|\^\s*3(?!\d)', $MS['pow3']
  $s = [regex]::Replace($s, '\^\s*(?:\{([^{}]+)\}|(-?\w))', [Text.RegularExpressions.MatchEvaluator]{ param($m) $x = if ($m.Groups[1].Success) { $m.Groups[1].Value } else { $m.Groups[2].Value }; Fill $MS['pown'] @{ n = ($x.Trim() -replace '^-', $MS['neg']) } })
  $s = $s -replace '_\s*\{([^{}]*)\}', '$1' -replace '_(\w)', '$1'
  $s = $s -replace '(\d)\s*:\s*(\d)', ('$1' + $MS['ratio'] + '$2')
  foreach ($c in $texCmds) { $s = $s -replace ([regex]::Escape($c) + '(?![a-zA-Z])'), (' ' + $MS[$c] + ' ') }
  $s = $s -replace '(?<=[a-zA-Z0-9\)\]\}])\s*-\s*(?=[\w\(\\])', (' ' + $MS['minus'] + ' ')
  $s = $s -replace '-(?=[\w\(\\])', $MS['neg']
  $s = $s -replace '\+', (' ' + $MS['plus'] + ' ')
  $s = $s -replace '\s*=\s*', (' ' + $MS['='] + ' ') -replace '\s*<\s*', (' ' + $MS['<'] + ' ') -replace '\s*>\s*', (' ' + $MS['>'] + ' ')
  $s = $s -replace '[{}]', '' -replace '\\([a-zA-Z]+)', '$1' -replace '\\', ''
  return (($s -replace '\s+', ' ').Trim())
}
function Speak-Math([string]$raw) {   # MathAnim narration: only the $...$ parts are TeX
  return [regex]::Replace($raw, '\$\$([^$]+)\$\$|\$([^$]+)\$', [Text.RegularExpressions.MatchEvaluator]{ param($m) $x = if ($m.Groups[1].Success) { $m.Groups[1].Value } else { $m.Groups[2].Value }; ' ' + (Speak-Tex $x) + ' ' })
}
function Speak-Symbols([string]$t) {   # plain text: unambiguous maths symbols only
  foreach ($c in $plainSyms) { $t = $t.Replace($c, ' ' + $MS[$c] + ' ') }
  if ($MS['=']) { $t = $t -replace '\s*=\s*', (' ' + $MS['='] + ' ') }
  if ($MS['<']) { $t = $t -replace '(?<=[\w\)])\s+<\s+(?=[\w\(-])', (' ' + $MS['<'] + ' ') -replace '(?<=[\w\)])\s+>\s+(?=[\w\(-])', (' ' + $MS['>'] + ' ') }
  return $t
}
function Prep([string]$t, [string]$raw = "") {
  if ($raw -and $MS.Count) { $t = Speak-Math ($raw -replace '<[^>]+>', '') }   # MathAnim step: read its TeX in words
  $t = (($t -replace '<[^>]+>', '') -replace '\s+', ' ').Trim()
  if ($MS.Count) { $t = Speak-Symbols $t }
  $c = { param($a) [string][char]$a }   # build the character classes at run time (keeps this file pure ASCII)
  $dot = & $c 0x3002; $comma = & $c 0xFF0C
  $cjk = (& $c 0x4E00) + '-' + (& $c 0x9FFF)
  $sym = (& $c 0xFE0F) + (& $c 0x200D) + (& $c 0x2600) + '-' + (& $c 0x27BF) + (& $c 0x2B00) + '-' + (& $c 0x2BFF) + (& $c 0x25A0) + '-' + (& $c 0x25FF)
  $emo = '[' + (& $c 0xD83C) + '-' + (& $c 0xD83E) + '][' + (& $c 0xDC00) + '-' + (& $c 0xDFFF) + ']'
  $arr = (& $c 0x2190) + '-' + (& $c 0x21FF)
  $zpun = (& $c 0x3002) + (& $c 0xFF01) + (& $c 0xFF1F) + (& $c 0xFF1B) + (& $c 0xFF1A) + (& $c 0xFF0C) + (& $c 0x3001)
  $zend = $cjk + (& $c 0x3000) + '-' + (& $c 0x303F) + (& $c 0xFF00) + '-' + (& $c 0xFFEF) + (& $c 0x201D) + (& $c 0x2019) + '\)'
  $t = $t -replace ($emo + '|[' + $sym + ']'), ' '
  if ($Lang -eq 'zh') {
    $t = $t -replace ('\s*[' + $arr + ']\s*'), $comma                        # arrows between steps -> pause
    $t = $t -replace ('([' + $zpun + '])\s*\.(\s+|$)'), '$1'                 # full stop + ". " left by .join('. ')
    $t = $t -replace ('(?<=[' + $zend + '])\s*\.(\s+|$)'), $dot
    $t = $t -replace ('\.\s+(?=[' + $cjk + '])'), $dot
  } else {
    $t = $t -replace ('\s*[' + $arr + ']\s*'), ', '
    $t = $t -replace ('\s*[' + (& $c 0x3002) + ']\s*'), '. ' -replace ('\s*[' + (& $c 0xFF0C) + (& $c 0x3001) + ']\s*'), ', ' -replace ('\s*[' + (& $c 0xFF1B) + ']\s*'), '; ' -replace ('\s*[' + (& $c 0xFF1A) + ']\s*'), ': '
    $t = $t -replace ('\s+[' + (& $c 0x00B7) + (& $c 0x2022) + ']\s+'), ', '   # "June 21 . longest day" separators
    $t = $t -replace '([.!?])\s*\.(?=\s|$)', '$1'
    $t = $t -replace '([.!?;:])\s*\.(\s+|$)', '$1$2'                       # "!. " left by .join('. ')
  }
  if (-not $isOpenAI) {   # home server: symbols it may choke on (a 6-min hang + GPU crash on a text with & % CO2 and a minus sign) -> the words a reader says
    $sub = (& $c 0x2080) + '-' + (& $c 0x2089)
    $t = [regex]::Replace($t, '[' + $sub + ']', { param($m) [string]([int][char]$m.Value[0] - 0x2080) })   # CO2 subscript -> CO2
    if ($Lang -eq 'zh') {
      $t = $t -replace '\s*&\s*', (& $c 0x548C) -replace ('\s*' + (& $c 0x2212) + '\s*'), (& $c 0x51CF)
      $t = $t -replace '(\d+(?:\.\d+)?)\s*%', ((& $c 0x767E) + (& $c 0x5206) + (& $c 0x4E4B) + '$1') -replace '%', ((& $c 0x767E) + (& $c 0x5206) + (& $c 0x6BD4))
    } else {
      $t = $t -replace '\s*&\s*', ' and ' -replace ('\s*' + (& $c 0x2212) + '\s*'), ' minus ' -replace '(\d)\s*%', '$1 percent' -replace '%', 'percent'
    }
    # symbols Qwen3-TTS skips, slurs or never stops on (TTS PC report TRANSCRIPT-ISSUES.md, 2026-11-19)
    $circ = '[' + (& $c 0x2460) + '-' + (& $c 0x2469) + ']'                       # circled 1..10
    $fplus = & $c 0xFF0B; $feq = & $c 0xFF1D; $ftil = & $c 0xFF5E; $lpar = & $c 0xFF08; $rpar = & $c 0xFF09
    $di = & $c 0x7B2C                                                              # di (ordinal prefix)
    if ($Lang -eq 'zh') {
      $num = @(0x4E00,0x4E8C,0x4E09,0x56DB,0x4E94,0x516D,0x4E03,0x516B,0x4E5D,0x5341) | ForEach-Object { & $c $_ }
      $t = [regex]::Replace($t, '(' + $di + '?)\s*(' + $circ + ')\s*', { param($m) $n = $num[[int][char]$m.Groups[2].Value[0] - 0x2460]; if ($m.Groups[1].Value) { $di + $n } else { $n + (& $c 0x3001) } })
      $t = $t -replace ('\s*' + $fplus + '\s*'), (& $c 0x52A0) -replace '(?<=[\d\)])\s*\+\s*(?=[\d\(])', (& $c 0x52A0)   # jia (not ion charges like H+)
      $t = $t -replace ('\s*' + $feq + '\s*'), ((& $c 0x7B49) + (& $c 0x4E8E))     # dengyu
      $t = $t -replace ('(\d)\s*[~' + $ftil + ']\s*(?=\d)'), ('$1' + (& $c 0x5230)) -replace ('[~' + $ftil + ']\s*(?=\d)'), (& $c 0x7EA6) -replace ('\s*[~' + $ftil + ']\s*'), (& $c 0x5230)
      $t = [regex]::Replace($t, '(\w+)\s*\^\s*\(?(-?\w+)\)?', { param($m) $m.Groups[1].Value + (& $c 0x7684) + $m.Groups[2].Value + (& $c 0x6B21) + (& $c 0x65B9) })
      $t = $t -replace '(?<=[\w\)])\s*<\s*(?=[\w\(-])', ((& $c 0x5C0F) + (& $c 0x4E8E)) -replace '(?<=[\w\)])\s*>\s*(?=[\w\(-])', ((& $c 0x5927) + (& $c 0x4E8E))
      $t = $t.Replace([string](& $c 0x1E41), (& $c 0x8D28) + (& $c 0x91CF) + (& $c 0x6D41) + (& $c 0x91CF)).Replace('v' + (& $c 0x2091), (& $c 0x55B7) + (& $c 0x6C14) + (& $c 0x901F) + (& $c 0x5EA6))
      # "neizhiwang (ER)" -> "neizhiwang, E R," : a pause and spelled letters
      $t = [regex]::Replace($t, '(?<=[' + $cjk + '])\s*[(' + $lpar + ']\s*([A-Za-z]{1,6})\s*[)' + $rpar + ']', { param($m) $w = $m.Groups[1].Value; $comma + $(if ($w -cmatch '^[A-Z]+$') { ($w.ToCharArray()) -join ' ' } else { $w }) + $comma })
      $t = $t -replace ($comma + '\s*([' + (& $c 0xFF1A) + (& $c 0xFF0C) + (& $c 0x3002) + (& $c 0x3001) + '])'), '$1'   # no double punctuation
      # fractions 2/3 -> san fen zhi er (not dates or units: plain digits on both sides only); 9/11 (the attacks) -> jiu yi yi
      $t = $t -replace '(?<![\d/.])9/11(?![\d/.])', ((& $c 0x4E5D) + (& $c 0x4E00) + (& $c 0x4E00))
      $t = [regex]::Replace($t, '(?<![\d/.])(\d+)\s*/\s*(\d+)(?![\d/.])', { param($m) $m.Groups[2].Value + (& $c 0x5206) + (& $c 0x4E4B) + $m.Groups[1].Value })
      # a single dash between two words ("hong-lv") -> enumeration comma; the long dash pair stays
      $t = $t -replace ('(?<=[' + $cjk + '])\s*[' + (& $c 0x2013) + (& $c 0x2014) + '](?![' + (& $c 0x2014) + '])\s*(?=[' + $cjk + '])'), (& $c 0x3001)
    } else {
      $words = 'one','two','three','four','five','six','seven','eight','nine','ten'
      $t = [regex]::Replace($t, '\s*(' + $circ + ')\s*', { param($m) ' ' + $words[[int][char]$m.Groups[1].Value[0] - 0x2460] + ', ' })
      $t = $t -replace ',\s*(?=[\)\].,;:!?]|$)', ''                         # "(step one, )." -> "(step one)."
      $t = $t -replace ('\s*' + $fplus + '\s*'), ' plus ' -replace ('\s*' + $feq + '\s*'), ' equals '
      $t = $t -replace ('(\d)\s*[~' + $ftil + ']\s*(?=\d)'), '$1 to ' -replace ('[~' + $ftil + ']\s*(?=\d)'), 'about ' -replace ('\s*[~' + $ftil + ']\s*'), ' to '
      $t = [regex]::Replace($t, '(\w+)\s*\^\s*\(?(-?\w+)\)?', { param($m) $m.Groups[1].Value + ' to the power of ' + $m.Groups[2].Value })
      $t = $t -replace '(?<=[\w\)])\s*<\s*(?=[\w\(-])', ' less than ' -replace '(?<=[\w\)])\s*>\s*(?=[\w\(-])', ' greater than '
      $t = $t.Replace([string](& $c 0x1E41), 'mass flow rate').Replace('v' + (& $c 0x2091), 'exhaust velocity')
      # fractions 1/6 -> one sixth, 2/3 -> two thirds; other a/b -> "a over b" (digits on both sides only)
      $t = $t -replace '(?<![\d/.])9/11(?![\d/.])', 'nine eleven'
      if ($t -match 'time signature|waltz|\bb\S{1,2}ny\S{1,2}n\b') {   # music: 3/4 is read "three four" (time signature), not a fraction
        $t = [regex]::Replace($t, '(?<![\d/.])([1-9])\s*/\s*([1-9])(?![\d/.])', { param($m) $words[[int]$m.Groups[1].Value - 1] + ' ' + $words[[int]$m.Groups[2].Value - 1] })
      }
      $t = [regex]::Replace($t, '(?<![\d/.])(\d+)\s*/\s*(\d+)(?![\d/.])', { param($m)
        $a = [int64]$m.Groups[1].Value; $b = [int64]$m.Groups[2].Value
        $ord = @{ 2='half'; 3='third'; 4='quarter'; 5='fifth'; 6='sixth'; 7='seventh'; 8='eighth'; 9='ninth'; 10='tenth'; 12='twelfth'; 100='hundredth'; 1000='thousandth' }
        if ($a -ge 1 -and $a -le 10 -and $a -lt $b -and $ord.ContainsKey([int]$b)) {
          $o = $ord[[int]$b]; if ($a -gt 1) { $o = if ($o -eq 'half') { 'halves' } else { $o + 's' } }
          $words[$a - 1] + ' ' + $o } else { "$a over $b" } })
    }
    $t = $t -replace ('[' + (& $c 0x2090) + '-' + (& $c 0x209C) + ']'), ''      # other subscript letters
  }
  $t = ($t -replace '\s+', ' ').Trim()
  if ($Lang -eq 'zh') {   # doubled full stops from .join() with a full stop after a sentence that already ends in one
    $t = $t -replace ('([' + (& $c 0x3002) + (& $c 0xFF01) + (& $c 0xFF1F) + (& $c 0xFF1B) + '])(\s*' + (& $c 0x3002) + ')+'), '$1'
  }
  if ($Lang -eq 'zh'){   # pinyin.js ruby text glued after a word (e.g. a word followed by its tone-marked pinyin) must not be read aloud
    $tone = ((0x101,0xE1,0x1CE,0xE0,0x113,0xE9,0x11B,0xE8,0x12B,0xED,0x1D0,0xEC,0x14D,0xF3,0x1D2,0xF2,0x16B,0xFA,0x1D4,0xF9,0x1D6,0x1D8,0x1DA,0x1DC,0xFC) | ForEach-Object { & $c $_ }) -join ''
    $t = $t -replace ('(?<=[' + $cjk + '])[A-Za-z' + $tone + ']*[' + $tone + '][A-Za-z' + $tone + ']*'), ''
    if ($Engine -eq 'openai') { $t = Fix-Poly $t }   # homophone swaps were for OpenAI; serena reads 多音字 correctly as written
  }
  return $t
}
