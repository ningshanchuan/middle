# Generate pre-recorded read-aloud audio with OpenAI gpt-4o-mini-tts for every collected text that has no file yet.
#   input : <Work>\texts_<lang>.jsonl (from collect_all.ps1 / merge.ps1) + extras_<lang>.txt next to this script (one text per line)
#   output: <Root>\audio\<lang>\<key>.mp3  +  manifest.js / manifest.json  (published with the site)
#           The API returns raw 24 kHz PCM; it is kept as <Work>\pcm_<lang>\<key>.wav (master, not published) and encoded
#           here with the Windows Media Foundation MP3 encoder: MPEG-2 Layer III, 24 kHz mono, 32 kbps (plays everywhere).
#   log   : <Work>\gen_<lang>.tsv  (key, chars, bytes, seconds, text sent to TTS)
# Usage:  powershell -ExecutionPolicy Bypass -File gen.ps1 -Estimate          (only count characters / minutes / cost)
#         powershell -ExecutionPolicy Bypass -File gen.ps1 [-Workers 6] [-Limit 20] [-MaxUSD 25]
#         powershell -ExecutionPolicy Bypass -File gen.ps1 -ManifestOnly     (rewrite the manifest from the files present)
#         powershell -ExecutionPolicy Bypass -File gen.ps1 -Prune            (delete clips whose text is no longer in any lesson)
# The API key is read from <Root>\OpenAI_key.txt (gitignored) inside the worker that calls the API; it is never printed or written.
param([string]$Lang = "zh", [switch]$Estimate, [switch]$ManifestOnly, [switch]$Prune, [int]$Workers = 6, [int]$Limit = 0, [double]$MaxUSD = 25,
      [string]$Voice = "marin", [double]$Speed = 0, [string]$Model = "gpt-4o-mini-tts", [string]$Format = "mp3", [int]$Kbps = 32,
      [double]$CharsPerSec = 0, [double]$UsdPerMin = 0.015,
      [string]$Endpoint = "https://api.openai.com/v1/audio/speech", [string]$Engine = "openai", [switch]$Replace,
      [int]$WorkerIndex = -1, [string]$Jobs = "", [string]$Root = "", [string]$Work = "")
# -Engine qwen3 -Endpoint http://<tts-server>:8000/v1/audio/speech -Voice serena -Model qwen3 : the home TTS server (OpenAI-compatible, no key, no cost).
# -Replace : re-record clips that already exist (e.g. switching to a new voice), in lesson order; finished keys are listed in
#            <Work>\done_<engine>_<lang>.txt so the run can be stopped and resumed. Masters of other engines go to pcm_<lang>_<engine>.
$ErrorActionPreference = 'Stop'
if (-not $Speed) { $Speed = if ($Lang -eq 'zh' -and $Engine -eq 'openai') { 0.9 } else { 1.0 } }   # home server (serena): user chose normal speed for both languages            # zh slower for a heritage learner; en natural pace
if (-not $CharsPerSec) { $CharsPerSec = if ($Lang -eq 'zh') { 3.0 } else { 14.0 } } # for the cost estimate only
$ProgressPreference = 'SilentlyContinue'   # Windows PowerShell's progress bar makes Invoke-WebRequest very slow
. (Join-Path $PSScriptRoot "paths.ps1")
$utf8 = New-Object Text.UTF8Encoding($false)
$audioDir = Join-Path $Root "audio\$Lang"; New-Item -ItemType Directory -Force $audioDir | Out-Null
$pcmDir = Join-Path $Work $(if ($Engine -eq "openai") { "pcm_$Lang" } else { "pcm_${Lang}_$Engine" }); New-Item -ItemType Directory -Force $pcmDir | Out-Null
$isOpenAI = $Endpoint -like "*api.openai.com*"
$doneFile = Join-Path $Work "done_${Engine}_$Lang.txt"

function Test-Mp3([string]$path) {   # true when the file starts with an MP3 frame (after an optional ID3 tag)
  if (-not (Test-Path $path) -or (Get-Item $path).Length -lt 400) { return $false }
  $b = [IO.File]::ReadAllBytes($path); $i = 0
  if ($b[0] -eq 0x49 -and $b[1] -eq 0x44 -and $b[2] -eq 0x33) { $i = 10 + (([int]$b[6] -shl 21) -bor ([int]$b[7] -shl 14) -bor ([int]$b[8] -shl 7) -bor [int]$b[9]) }
  return ($i + 1 -lt $b.Length -and $b[$i] -eq 0xFF -and ([int]$b[$i+1] -band 0xE0) -eq 0xE0)
}
function Write-Manifest {
  $keys = @(Get-ChildItem $audioDir -Filter "*.$Format" | Where-Object { $_.Length -gt 200 -and $_.BaseName -match '^[0-9a-f]{8}$' } | ForEach-Object { $_.BaseName } | Sort-Object)
  $mb = [Math]::Round(((Get-ChildItem $audioDir -Filter "*.$Format" | Measure-Object Length -Sum).Sum) / 1MB, 1)
  $head = '"lang":"' + $Lang + '","ext":"' + $Format + '","model":"' + $Model + '","voice":"' + $Voice + '","speed":' + $Speed + ',"count":' + $keys.Count
  [IO.File]::WriteAllText((Join-Path $audioDir "manifest.js"), "/* generated by tools/tts/gen.ps1 - list of pre-recorded read-aloud clips (key = FNV-1a of lang|text, see shared/lab.js) */`nLabAudioManifest({" + $head + ',"keys":"' + ($keys -join ' ') + '"});' + "`n", $utf8)
  [IO.File]::WriteAllText((Join-Path $audioDir "manifest.json"), "{" + $head + ',"keys":[' + (($keys | ForEach-Object { '"' + $_ + '"' }) -join ',') + "]}`n", $utf8)
  "manifest: $($keys.Count) clips, $mb MB in $audioDir"
}

# ---------------- worker: one process per slice of the job list ----------------
if ($WorkerIndex -ge 0) {
  # Windows Media Foundation MP3 encoder through WinRT (Windows 10/11)
  Add-Type -AssemblyName System.Runtime.WindowsRuntime
  $null = [Windows.Storage.StorageFile, Windows.Storage, ContentType = WindowsRuntime]
  $null = [Windows.Media.Transcoding.MediaTranscoder, Windows.Media.Transcoding, ContentType = WindowsRuntime]
  $null = [Windows.Media.MediaProperties.MediaEncodingProfile, Windows.Media.MediaProperties, ContentType = WindowsRuntime]
  $ext = [System.WindowsRuntimeSystemExtensions].GetMethods() | Where-Object { $_.Name -eq 'AsTask' -and $_.GetParameters().Count -eq 1 }
  $asOp = ($ext | Where-Object { $_.GetParameters()[0].ParameterType.Name -eq 'IAsyncOperation`1' })[0]
  $asProg = ($ext | Where-Object { $_.GetParameters()[0].ParameterType.Name -eq 'IAsyncActionWithProgress`1' })[0]
  function Await($op, [Type]$t) { $task = $asOp.MakeGenericMethod($t).Invoke($null, @($op)); if (-not $task.Wait(120000)) { throw "WinRT timeout" }; $task.Result }
  function Convert-ToMp3([string]$wav, [string]$mp3) {
    $src = Await ([Windows.Storage.StorageFile]::GetFileFromPathAsync($wav)) ([Windows.Storage.StorageFile])
    $dir = Await ([Windows.Storage.StorageFolder]::GetFolderFromPathAsync((Split-Path $mp3))) ([Windows.Storage.StorageFolder])
    $dst = Await ($dir.CreateFileAsync((Split-Path $mp3 -Leaf), [Windows.Storage.CreationCollisionOption]::ReplaceExisting)) ([Windows.Storage.StorageFile])
    $p = [Windows.Media.MediaProperties.MediaEncodingProfile]::CreateMp3([Windows.Media.MediaProperties.AudioEncodingQuality]::Low)
    $p.Audio.Bitrate = [uint32]($Kbps * 1000); $p.Audio.ChannelCount = 1; $p.Audio.SampleRate = [uint32]24000
    $prep = Await ((New-Object Windows.Media.Transcoding.MediaTranscoder).PrepareFileTranscodeAsync($src, $dst, $p)) ([Windows.Media.Transcoding.PrepareTranscodeResult])
    if (-not $prep.CanTranscode) { throw "cannot transcode: $($prep.FailureReason)" }
    $t = $asProg.MakeGenericMethod([double]).Invoke($null, @($prep.TranscodeAsync())); if (-not $t.Wait(120000)) { throw "transcode timeout" }
  }
  function Write-Wav([string]$pcm, [string]$wav) {   # OpenAI "pcm" = 24 kHz, 16-bit signed little-endian, mono
    $d = [IO.File]::ReadAllBytes($pcm); $ms = New-Object IO.MemoryStream; $w = New-Object IO.BinaryWriter($ms)
    $w.Write([Text.Encoding]::ASCII.GetBytes('RIFF')); $w.Write([int](36 + $d.Length)); $w.Write([Text.Encoding]::ASCII.GetBytes('WAVEfmt '))
    $w.Write([int]16); $w.Write([int16]1); $w.Write([int16]1); $w.Write([int]24000); $w.Write([int]48000); $w.Write([int16]2); $w.Write([int16]16)
    $w.Write([Text.Encoding]::ASCII.GetBytes('data')); $w.Write([int]$d.Length); $w.Write($d); $w.Flush()
    [IO.File]::WriteAllBytes($wav, $ms.ToArray())
  }
  $key = if ($isOpenAI) { ([IO.File]::ReadAllText($KeyFile)).Trim() } else { "" }
  $insFile = Join-Path $PSScriptRoot "instructions_${Lang}_$Engine.txt"; if ($isOpenAI -and -not (Test-Path $insFile)) { $insFile = Join-Path $PSScriptRoot "instructions_$Lang.txt" }
  $ins = if (Test-Path $insFile) { [IO.File]::ReadAllText($insFile, [Text.Encoding]::UTF8).Trim() } else { "" }   # serena: style instructions made Chinese sound wrong -> none
  $done = @{}; if ($Replace -and (Test-Path $doneFile)) { foreach ($d in [IO.File]::ReadAllLines($doneFile)) { $done[$d.Trim()] = 1 } }
  # skip_<engine>_<lang>.txt: keys that hang / crash the home server (recorded separately, one at a time); treated like done here
  $skipFile = Join-Path $Work "skip_${Engine}_$Lang.txt"; if ($Replace -and (Test-Path $skipFile)) { foreach ($d in [IO.File]::ReadAllLines($skipFile)) { if ($d.Trim()) { $done[$d.Trim()] = 1 } } }
  $lines = [IO.File]::ReadAllLines($Jobs, [Text.Encoding]::UTF8)
  $log = Join-Path $Work ("gen_{0}_w{1}.tsv" -f $Lang, $WorkerIndex)
  for ($i = $WorkerIndex; $i -lt $lines.Count; $i += $Workers) {
    $k, $inp = $lines[$i] -split "`t", 2
    $out = Join-Path $audioDir "$k.$Format"
    if ($Replace) { if ($done.ContainsKey($k)) { continue } } elseif (Test-Mp3 $out) { continue }
    $wav = Join-Path $pcmDir "$k.wav"; $raw = "$wav.pcm"; $part = Join-Path $audioDir "$k.part.$Format"
    $req = @{ model = $Model; voice = $Voice; input = $inp; response_format = 'pcm'; speed = $Speed }; if ($ins) { $req.instructions = $ins }; if (-not $isOpenAI) { $req.language = $Lang }
    $body = $req | ConvertTo-Json -Compress
    $hdrs = if ($isOpenAI) { @{ Authorization = "Bearer $key" } } else { @{} }
    $ok = $false
    for ($a = 1; $a -le 5 -and -not $ok; $a++) {
      # home server: while it is down or its GPU guard is paused, wait here (do not burn the tries and skip the clip)
      if (-not $isOpenAI) { $hu = $Endpoint -replace '/v1/.*$', '/health'; $waited = 0; while ($true) { try { $h = Invoke-RestMethod $hu -TimeoutSec 15; if ($h.gpu_guard.ok) { break } } catch {}; if (-not $waited) { "WAIT server down or GPU paused" }; $waited++; Start-Sleep 60 } }
      # home server: some very short texts (e.g. the single word "mitochondria.") make the model never stop. Retries send the same
      # words written slightly differently (capital first letter / no final full stop / both); the clip keeps the original key.
      $send = $inp
      if (-not $isOpenAI -and $a -ge 2 -and $Lang -eq 'en' -and $inp.Length -lt 40) {
        $cap = $inp.Substring(0, 1).ToUpper() + $inp.Substring(1); $nod = $inp.TrimEnd('.', ' ')
        $send = @($inp, $inp, $cap, $nod, ($cap.TrimEnd('.', ' ') + '!'), $cap)[$a]
        $body = ($req.Clone() | ForEach-Object { $_.input = $send; $_ } | ConvertTo-Json -Compress)
      }
      $tmo = if (-not $isOpenAI -and $inp.Length -lt 40) { 75 } else { [int](180 + 8 * $inp.Length / $(if ($Lang -eq 'zh') { 4 } else { 14 })) }   # long texts (600+ chars, ~50 s of speech) need more than 3 min; a short one that takes 75 s is stuck
      try {
        if (-not (Test-Path $wav)) {     # a master from an earlier run is re-used (no second API call)
          # home server crashes easily: one machine-wide lock makes every worker (en and zh) take turns = a serial queue
          $mx = $null; if (-not $isOpenAI) { $mx = New-Object Threading.Mutex($false, 'Global\SerenaTTSQueue'); try { [void]$mx.WaitOne() } catch [Threading.AbandonedMutexException] {} }
          try { Invoke-WebRequest -Uri $Endpoint -Method Post -Headers $hdrs -ContentType 'application/json; charset=utf-8' -Body ([Text.Encoding]::UTF8.GetBytes($body)) -OutFile $raw -UseBasicParsing -TimeoutSec $tmo }
          finally { if ($mx) { $mx.ReleaseMutex(); $mx.Dispose() } }
          if ((Get-Item $raw).Length -lt 4800) { throw "audio too short" }
          # sanity check: a clip far too long (garbled / stretched) or too short (cut off) for its text is generated again
          $rs = ((Get-Item $raw).Length / 48000.0); $cps = $inp.Length / [Math]::Max(0.1, $rs)
          $lo, $hi = if ($Lang -eq 'zh') { 2.8, 9 } else { 7, 22 }
          if (-not $isOpenAI -and $inp.Length -ge 8 -and ($cps -lt $lo -or $cps -gt $hi) -and $a -lt 4) { Remove-Item $raw -Force; throw ("odd length {0:N1}s for {1} chars ({2:N1}/s)" -f $rs, $inp.Length, $cps) }
          Write-Wav $raw $wav; Remove-Item $raw -Force
        }
        $sec = [Math]::Round(((Get-Item $wav).Length - 44) / 48000.0, 2)
        Convert-ToMp3 $wav $part
        for ($w8 = 0; $w8 -lt 20; $w8++) { try { [IO.File]::Open($part, 'Open', 'Read', 'None').Dispose(); break } catch { Start-Sleep -Milliseconds 150 } }   # encoder may still hold the file
        if (-not (Test-Mp3 $part)) { throw "encoder produced no MP3" }
        Move-Item $part $out -Force; $ok = $true
        [IO.File]::AppendAllText($log, ("{0}`t{1}`t{2}`t{3}`t{4}`n" -f $k, $inp.Length, (Get-Item $out).Length, $sec, $inp), $utf8)
        if ($Replace) { [IO.File]::AppendAllText($doneFile, "$k`n", $utf8) }
        "OK $k chars=$($inp.Length) sec=$sec"
      } catch {
        $code = 0; try { $code = [int]$_.Exception.Response.StatusCode } catch {}
        Remove-Item $raw, $part -Force -ErrorAction SilentlyContinue
        "ERR $k try=$a status=$code $($_.Exception.Message)"
        if ($code -eq 400 -or $code -eq 401 -or $code -eq 403) { break }      # bad request / key problem: do not hammer
        # home server: 502/503/504 = its speech engine is down even if /health says ok: wait (do not use up the tries and skip the clip)
        if (-not $isOpenAI -and ($code -eq 502 -or $code -eq 503 -or $code -eq 504)) { if ($a -gt 1) { "WAIT speech engine down ($code)" }; $a--; Start-Sleep 120; continue }
        Start-Sleep -Seconds $(if ($code -eq 429) { 15 * $a } else { 4 * $a })
      }
    }
    Start-Sleep -Milliseconds 150
  }
  exit 0
}

